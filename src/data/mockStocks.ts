export function generateStockCandles(
  stock: StockItem,
  count: number = 90,
  timeframe: '15m' | '1H' | '1D' | '1W' | '1M' = '1D'
): CandleData[] {
  const candles: CandleData[] = [];
  const basePrice = stock.price || (stock.currency === 'KRW' ? 100000 : 150);
  const isKR = stock.market === 'KR';

  const now = Date.now();
  const stepMs =
    timeframe === '15m'
      ? 15 * 60 * 1000
      : timeframe === '1H'
      ? 60 * 60 * 1000
      : timeframe === '1D'
      ? 24 * 60 * 60 * 1000
      : timeframe === '1W'
      ? 7 * 24 * 60 * 60 * 1000
      : 30 * 24 * 60 * 60 * 1000;

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const dateObj = new Date(timestamp);
    let dateStr = '';
    if (timeframe === '15m' || timeframe === '1H') {
      dateStr = `${dateObj.getMonth() + 1}/${dateObj.getDate()} ${String(dateObj.getHours()).padStart(2, '0')}:${String(dateObj.getMinutes()).padStart(2, '0')}`;
    } else {
      dateStr = `${dateObj.getFullYear()}-${String(dateObj.getMonth() + 1).padStart(2, '0')}-${String(dateObj.getDate()).padStart(2, '0')}`;
    }

    const price = basePrice;
    candles.push({
      timestamp,
      date: dateStr,
      open: isKR ? Math.round(price) : Number(price.toFixed(2)),
      high: isKR ? Math.round(price * 1.002) : Number((price * 1.002).toFixed(2)),
      low: isKR ? Math.round(price * 0.998) : Number((price * 0.998).toFixed(2)),
      close: isKR ? Math.round(price) : Number(price.toFixed(2)),
      volume: stock.volume,
    });
  }

  // Ensure the very last candle matches current price
  if (candles.length > 0) {
    candles[candles.length - 1].close = stock.price;
    candles[candles.length - 1].open = (stock.price - (stock.change || 0)) || stock.price;
  }

  return enrichCandleData(candles);
}

